"""
CDP で起動中の Chrome から Netscape 形式の cookies.txt を書き出す。

Chrome を閉じずに取得できる（--cookies-from-browser とは別経路）。
launch_chrome_cdp.py と同じ CDP エンドポイント・プロファイルを想定。

例:
  python scripts/export_cookies_cdp.py
  python scripts/export_cookies_cdp.py --out cookies.txt
  python scripts/export_cookies_cdp.py --shared-mp4

環境変数（任意）:
  CDP_ENDPOINT  既定 http://127.0.0.1:9222
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import urllib.error
import urllib.request
from pathlib import Path
from typing import Any

PROJECT_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_CDP = "http://127.0.0.1:9222"
_NETSCAPE_HEADER = """# Netscape HTTP Cookie File
# This file was generated by export_cookies_cdp.py.  Do not edit.

"""
_AUTH_COOKIE_KEYS = frozenset({"LOGIN_INFO", "SID", "__Secure-1PSID", "__Secure-3PSID"})


def _import_downloader():
    if str(PROJECT_ROOT) not in sys.path:
        sys.path.insert(0, str(PROJECT_ROOT))
    from yt_transcript import downloader as dl

    return dl


def cdp_json(endpoint: str, path: str) -> Any:
    url = endpoint.rstrip("/") + path
    try:
        with urllib.request.urlopen(url, timeout=5) as resp:
            return json.loads(resp.read().decode("utf-8"))
    except urllib.error.URLError as exc:
        raise SystemExit(
            f"CDP に接続できません: {url}\n"
            f"  launch_chrome_cdp.py で Chrome を起動しているか確認してください。\n"
            f"  ({exc})"
        ) from exc


def pick_page_target(pages: list[dict], url_contains: str | None) -> dict:
    page_targets = [p for p in pages if p.get("type") == "page" and p.get("webSocketDebuggerUrl")]
    if not page_targets:
        raise SystemExit(
            "CDP に page ターゲットがありません。Chrome でタブを 1 つ以上開いてください。"
        )
    if url_contains:
        needle = url_contains.lower()
        for p in page_targets:
            if needle in (p.get("url") or "").lower():
                return p
    return page_targets[0]


class CdpSession:
    def __init__(self, ws_url: str) -> None:
        try:
            import websocket
        except ImportError as exc:
            raise SystemExit(
                "websocket-client が必要です: pip install websocket-client"
            ) from exc
        self._ws = websocket.create_connection(ws_url, timeout=30)
        self._next_id = 0

    def close(self) -> None:
        self._ws.close()

    def call(self, method: str, params: dict | None = None) -> dict:
        self._next_id += 1
        msg_id = self._next_id
        self._ws.send(
            json.dumps({"id": msg_id, "method": method, "params": params or {}})
        )
        while True:
            raw = self._ws.recv()
            msg = json.loads(raw)
            if msg.get("id") != msg_id:
                continue
            if "error" in msg:
                err = msg["error"]
                raise RuntimeError(f"{method}: {err.get('message', err)}")
            return msg.get("result") or {}


def fetch_all_cookies(ws_url: str) -> list[dict]:
    session = CdpSession(ws_url)
    try:
        session.call("Network.enable")
        result = session.call("Network.getAllCookies")
        return list(result.get("cookies") or [])
    finally:
        session.close()


def dedupe_cookies(cookies: list[dict]) -> list[dict]:
    merged: dict[tuple[str, str, str], dict] = {}
    for c in cookies:
        key = (c.get("domain", ""), c.get("path", "/"), c.get("name", ""))
        merged[key] = c
    return list(merged.values())


def netscape_line(cookie: dict) -> str:
    domain = cookie.get("domain") or ""
    if cookie.get("httpOnly"):
        domain = f"#HttpOnly_{domain}"
    raw_domain = cookie.get("domain") or ""
    include_sub = "TRUE" if raw_domain.startswith(".") else "FALSE"
    path = cookie.get("path") or "/"
    secure = "TRUE" if cookie.get("secure") else "FALSE"
    expires = cookie.get("expires", -1)
    if cookie.get("session") or expires is None or expires <= 0:
        expires_at = "0"
    else:
        expires_at = str(int(expires))
    name = cookie.get("name", "")
    value = cookie.get("value", "")
    return "\t".join((domain, include_sub, path, secure, expires_at, name, value))


def write_cookies_txt(path: Path, cookies: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [netscape_line(c) for c in sorted(cookies, key=lambda c: (c.get("domain", ""), c.get("name", "")))]
    path.write_text(_NETSCAPE_HEADER + "\n".join(lines) + ("\n" if lines else ""), encoding="utf-8")


def summarize_youtube(path: Path) -> tuple[int, set[str]]:
    dl = _import_downloader()
    names = dl.youtube_cookie_names(path)
    return len(names), names


def default_output_path(shared_mp4: bool) -> Path:
    if shared_mp4:
        return (PROJECT_ROOT.parent / "py_youtube_dl_mp4" / "cookies.txt").resolve()
    return (PROJECT_ROOT / "cookies.txt").resolve()


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="CDP 起動中の Chrome から cookies.txt を書き出す"
    )
    parser.add_argument(
        "--endpoint",
        default=os.environ.get("CDP_ENDPOINT", DEFAULT_CDP),
        help=f"CDP HTTP エンドポイント（既定: {DEFAULT_CDP}）",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=None,
        help="出力先（未指定時はリポジトリ直下 cookies.txt）",
    )
    parser.add_argument(
        "--shared-mp4",
        action="store_true",
        help="../py_youtube_dl_mp4/cookies.txt に出力（mp4 プロジェクトと共有）",
    )
    parser.add_argument(
        "--page-url-contains",
        default="youtube.com",
        metavar="TEXT",
        help="Cookie 取得に使うタブ（URL に含まれる文字列。空で先頭タブ）",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    endpoint = str(args.endpoint).strip().strip('"').strip("'") or DEFAULT_CDP
    out_path = args.out
    if out_path is None:
        out_path = default_output_path(args.shared_mp4)
    else:
        out_path = out_path.expanduser().resolve()

    pages = cdp_json(endpoint, "/json/list")
    if not isinstance(pages, list):
        raise SystemExit("CDP /json/list の応答が不正です。")

    hint = (args.page_url_contains or "").strip() or None
    target = pick_page_target(pages, hint)
    print(f"CDP ターゲット: {target.get('url', '(no url)')[:100]}")

    cookies = dedupe_cookies(fetch_all_cookies(target["webSocketDebuggerUrl"]))
    write_cookies_txt(out_path, cookies)
    print(f"書き出し: {out_path} ({len(cookies)} 件)")

    yt_count, yt_names = summarize_youtube(out_path)
    if yt_count == 0:
        print(
            "警告: .youtube.com の Cookie がありません。"
            " YouTube タブを開いてから再実行してください。",
            file=sys.stderr,
        )
    elif not (_AUTH_COOKIE_KEYS & yt_names):
        print(
            "警告: YouTube ログイン Cookie (LOGIN_INFO / SID 等) が見つかりません。"
            " YouTube にログインした状態で再実行してください。",
            file=sys.stderr,
        )
    else:
        found = sorted(_AUTH_COOKIE_KEYS & yt_names)
        print(f"YouTube 認証 Cookie: {', '.join(found)} ({yt_count} 件の .youtube.com 行)")


if __name__ == "__main__":
    main()
